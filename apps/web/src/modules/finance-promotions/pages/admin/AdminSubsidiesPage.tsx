import React, { useState, useEffect } from 'react';
import { Gift } from 'lucide-react';
import {
  adminPromotionApi,
  PlatformSubsidyRecord,
} from '../../api/financePromotionsApi.js';
import { SubsidyStatusBadge } from '../../components/FinanceStatusBadge.js';
import { formatLKR } from '../../../customer-experience/utils/formatters.js';
import {
  Alert,
  EmptyState,
  PageHeader,
} from '../../../../shared/components/index.js';

export const AdminSubsidiesPage: React.FC = () => {
  const [subsidies, setSubsidies] = useState<PlatformSubsidyRecord[]>([]);
  const [totalAccrued, setTotalAccrued] = useState(0);
  const [totalSettled, setTotalSettled] = useState(0);
  const [isLoading, setIsLoading] = useState(true);
  const [errorMessage, setErrorMessage] = useState<string | null>(null);

  useEffect(() => {
    setIsLoading(true);
    adminPromotionApi
      .getSubsidies({ limit: 25 })
      .then((res) => {
        if (res.success && res.data) {
          setSubsidies(res.data.subsidies || []);
          setTotalAccrued(res.data.totalAccruedInCents || 0);
          setTotalSettled(res.data.totalSettledInCents || 0);
        }
      })
      .catch((err: any) => {
        setErrorMessage(err?.message || 'Unable to load platform subsidies.');
      })
      .finally(() => setIsLoading(false));
  }, []);

  return (
    <div className="space-y-6">
      <PageHeader
        title="Platform Promotional Subsidies"
        subtitle="Audit discounts funded by AutoDock and reimbursed to seller accounts"
        backTo="/admin/finance"
        backLabel="Finance Overview"
      />

      {errorMessage && <Alert variant="danger">{errorMessage}</Alert>}

      <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
        <div className="bg-white border border-slate-200 rounded-lg p-5">
          <p className="text-xs text-slate-500">Accrued Subsidy Liability</p>
          <p className="text-xl font-bold text-slate-900 tabular-nums mt-1">
            {formatLKR(totalAccrued)}
          </p>
        </div>
        <div className="bg-white border border-slate-200 rounded-lg p-5">
          <p className="text-xs text-slate-500">Settled to Merchants</p>
          <p className="text-xl font-bold text-emerald-700 tabular-nums mt-1">
            {formatLKR(totalSettled)}
          </p>
        </div>
      </div>

      {isLoading ? (
        <div className="h-56 bg-white border border-slate-200 rounded-lg" />
      ) : subsidies.length === 0 ? (
        <EmptyState
          icon={<Gift className="w-6 h-6" />}
          title="No subsidy ledger entries yet"
          description="Reimbursements generated by AutoDock-funded coupons will appear here."
        />
      ) : (
        <div className="bg-white border border-slate-200 rounded-lg overflow-hidden">
          <div className="overflow-x-auto">
            <table className="w-full text-left border-collapse text-sm">
              <thead>
                <tr className="bg-slate-50 border-b border-slate-200 text-xs font-semibold text-slate-500 uppercase">
                  <th className="py-3 px-4">Reference</th>
                  <th className="py-3 px-4">Seller</th>
                  <th className="py-3 px-4">Campaign</th>
                  <th className="py-3 px-4">Subsidy</th>
                  <th className="py-3 px-4">Status</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-200">
                {subsidies.map((s) => {
                  const sellerName =
                    typeof s.sellerId === 'object'
                      ? s.sellerId.businessName || s.sellerId.storeName || 'Seller'
                      : s.sellerId;
                  return (
                    <tr key={s._id}>
                      <td className="py-3 px-4 font-mono text-xs font-semibold text-slate-900">
                        {s.subsidyReference}
                      </td>
                      <td className="py-3 px-4 text-slate-800 font-medium">
                        {sellerName}
                      </td>
                      <td className="py-3 px-4 font-mono text-xs text-blue-700">
                        {s.promotionCode}
                      </td>
                      <td className="py-3 px-4 font-semibold tabular-nums">
                        {formatLKR(s.subsidyAmountInCents)}
                      </td>
                      <td className="py-3 px-4">
                        <SubsidyStatusBadge status={s.status} />
                      </td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </div>
        </div>
      )}
    </div>
  );
};
